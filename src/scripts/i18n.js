export function getLang() {
  return localStorage.getItem('gtbg_lang') || 'es';
}

export function applyLang(lang) {
  const elements = document.querySelectorAll('[data-i18n]');

  // Fase 1: fade out
  elements.forEach(el => {
    el.style.opacity = '0';
  });

  // Fase 2: después del fade out, cambiar el texto y hacer fade in
  setTimeout(() => {
    document.documentElement.lang = lang;

    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const entry = translations[key];
      if (!entry) {
        el.style.opacity = '1';
        return;
      }
      const text = entry[lang] ?? entry.es;
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = text;
      } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.setAttribute('placeholder', text);
      } else {
        el.textContent = text;
      }
      el.style.opacity = '1';
    });

    localStorage.setItem('gtbg_lang', lang);

    document.querySelectorAll('.lang-toggle').forEach(toggle => {
      toggle.setAttribute('data-active', lang);
      toggle.querySelectorAll('.lang-opt').forEach(opt => {
        opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
      });
    });
  }, 180);
}

export function initLang() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const entry = translations[key];
    if (!entry) return;
    const text = entry[lang] ?? entry.es;
    if (el.hasAttribute('data-i18n-html')) {
      el.innerHTML = text;
    } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.setAttribute('placeholder', text);
    } else {
      el.textContent = text;
    }
  });
  document.querySelectorAll('.lang-toggle').forEach(toggle => {
    toggle.setAttribute('data-active', lang);
    toggle.querySelectorAll('.lang-opt').forEach(opt => {
      opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });
  });
}

export function toggleLang() {
  applyLang(getLang() === 'es' ? 'en' : 'es');
}